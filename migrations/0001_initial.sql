CREATE TABLE admin_revision (
    id INTEGER PRIMARY KEY CHECK (id=1),
    revision BIGINT NOT NULL DEFAULT 0
);
INSERT INTO admin_revision(id) VALUES(1);
CREATE FUNCTION bump_admin_revision() RETURNS trigger LANGUAGE plpgsql
SECURITY DEFINER SET search_path=public,pg_temp AS $$
BEGIN
    UPDATE admin_revision SET revision=revision+1 WHERE id=1;
    RETURN NULL;
END $$;
CREATE TRIGGER product_curation_revision AFTER INSERT OR UPDATE OR DELETE ON product_curation
    FOR EACH STATEMENT EXECUTE FUNCTION bump_admin_revision();
CREATE TRIGGER roadmap_revision AFTER INSERT OR UPDATE OR DELETE ON roadmap_features
    FOR EACH STATEMENT EXECUTE FUNCTION bump_admin_revision();
CREATE TRIGGER retailers_revision AFTER INSERT OR UPDATE OR DELETE ON retailers
    FOR EACH STATEMENT EXECUTE FUNCTION bump_admin_revision();
CREATE TRIGGER scrape_review_revision AFTER INSERT OR UPDATE OR DELETE ON scrape_error_reviews
    FOR EACH STATEMENT EXECUTE FUNCTION bump_admin_revision();

