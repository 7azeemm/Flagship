-- Initial PostgreSQL schema for a fresh Flagship database.
-- Rust owns application tables; Directus owns its directus_* system tables.
CREATE TABLE products (
    id TEXT PRIMARY KEY NOT NULL,
    section TEXT NOT NULL,
    retailer TEXT NOT NULL,
    url TEXT NOT NULL,
    price INTEGER NOT NULL,
    status TEXT NOT NULL,
    removed BOOLEAN NOT NULL DEFAULT false,
    payload TEXT NOT NULL,
    title TEXT GENERATED ALWAYS AS (payload::jsonb->>'title') STORED,
    description TEXT GENERATED ALWAYS AS (payload::jsonb->>'description') STORED,
    image TEXT GENERATED ALWAYS AS (payload::jsonb->>'image') STORED,
    components JSONB GENERATED ALWAYS AS (payload::jsonb->'components') STORED
);

CREATE INDEX products_section_idx ON products(section) WHERE removed = false;
CREATE INDEX products_retailer_idx ON products(retailer) WHERE removed = false;
CREATE INDEX products_url_idx ON products(url);
CREATE INDEX products_price_idx ON products(price) WHERE removed = false;

CREATE TABLE variants (
    id TEXT PRIMARY KEY NOT NULL,
    payload TEXT NOT NULL
);

CREATE TABLE product_info_cache (
    url TEXT PRIMARY KEY NOT NULL,
    expires_at TEXT NOT NULL,
    payload TEXT NOT NULL
);

CREATE INDEX product_info_cache_expiry_idx ON product_info_cache(expires_at);

CREATE TABLE app_state (
    key TEXT PRIMARY KEY NOT NULL,
    payload TEXT NOT NULL
);

CREATE TABLE users (
    id TEXT PRIMARY KEY NOT NULL,
    email TEXT NOT NULL UNIQUE CONSTRAINT users_email_normalized CHECK (email = lower(email)),
    display_name TEXT,
    given_name TEXT,
    family_name TEXT,
    avatar_url TEXT,
    password_hash TEXT,
    email_verified_at TEXT,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);

CREATE TABLE auth_identities (
    id TEXT PRIMARY KEY NOT NULL,
    user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    provider TEXT NOT NULL,
    provider_subject TEXT NOT NULL,
    provider_email TEXT NOT NULL,
    created_at TEXT NOT NULL,
    UNIQUE(provider, provider_subject)
);
CREATE INDEX auth_identities_user_idx ON auth_identities(user_id);

CREATE TABLE sessions (
    id TEXT PRIMARY KEY NOT NULL,
    user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token_hash TEXT NOT NULL UNIQUE,
    csrf_hash TEXT NOT NULL,
    expires_at TEXT NOT NULL,
    last_seen_at TEXT NOT NULL,
    user_agent TEXT,
    created_at TEXT NOT NULL
);
CREATE INDEX sessions_user_idx ON sessions(user_id);
CREATE INDEX sessions_expiry_idx ON sessions(expires_at);

CREATE TABLE email_tokens (
    id TEXT PRIMARY KEY NOT NULL,
    user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    purpose TEXT NOT NULL CHECK(purpose IN ('verify_email', 'reset_password')),
    token_hash TEXT NOT NULL UNIQUE,
    expires_at TEXT NOT NULL,
    used_at TEXT,
    created_at TEXT NOT NULL
);
CREATE INDEX email_tokens_user_purpose_idx ON email_tokens(user_id, purpose);
CREATE INDEX email_tokens_expiry_idx ON email_tokens(expires_at);

CREATE TABLE wishlist_items (
    user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    target_type TEXT NOT NULL CHECK(target_type IN ('variant', 'product')),
    target_id TEXT NOT NULL,
    created_at TEXT NOT NULL,
    PRIMARY KEY(user_id, target_type, target_id)
);
CREATE INDEX wishlist_items_user_created_idx ON wishlist_items(user_id, created_at DESC);

CREATE TABLE oauth_attempts (
    state_hash TEXT PRIMARY KEY NOT NULL,
    nonce TEXT NOT NULL,
    return_to TEXT NOT NULL,
    link_user_id TEXT REFERENCES users(id) ON DELETE CASCADE,
    browser_hash TEXT,
    expires_at TEXT NOT NULL,
    created_at TEXT NOT NULL
);
CREATE INDEX oauth_attempts_expiry_idx ON oauth_attempts(expires_at);

-- Delivery status for security notifications; no passwords or tokens are stored here.
CREATE TABLE account_notifications (
    id TEXT PRIMARY KEY NOT NULL,
    user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind TEXT NOT NULL CHECK(kind IN ('welcome', 'password_changed')),
    created_at TEXT NOT NULL,
    sent_at TEXT,
    attempts BIGINT NOT NULL DEFAULT 0,
    next_attempt_at TEXT NOT NULL,
    lease_token TEXT,
    lease_until TEXT
);
CREATE INDEX account_notifications_pending ON account_notifications(sent_at, next_attempt_at);

-- Shopping alerts are independent of wishlists and security mail.

CREATE TABLE alert_events (
    sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_key TEXT NOT NULL UNIQUE,
    section TEXT NOT NULL,
    product_id TEXT NOT NULL,
    observed_at TEXT NOT NULL,
    payload TEXT NOT NULL,
    batch_id TEXT
);
CREATE TABLE alerts (
    id TEXT PRIMARY KEY NOT NULL,
    user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    rule TEXT NOT NULL,
    state TEXT NOT NULL CHECK(state IN ('active','paused','pending','delivered','failed','expired')),
    cursor BIGINT NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL,
    expires_at TEXT NOT NULL,
    last_match TEXT,
    last_matched_at TEXT,
    last_delivery_at TEXT,
    lowest_seen INTEGER
);
CREATE INDEX alerts_user ON alerts(user_id, created_at DESC);
CREATE INDEX alerts_active ON alerts(state, cursor);
CREATE TABLE alert_deliveries (
    alert_id TEXT PRIMARY KEY NOT NULL REFERENCES alerts(id) ON DELETE CASCADE,
    payload TEXT NOT NULL,
    attempts BIGINT NOT NULL DEFAULT 0,
    next_attempt_at TEXT NOT NULL,
    lease_token TEXT,
    lease_until TEXT,
    sent_at TEXT
);
CREATE INDEX alert_delivery_pending ON alert_deliveries(sent_at,next_attempt_at);

-- Store each tracked scrape error independently; retain app_state for the
-- optional scanner cache and product overrides used elsewhere in the app.
CREATE TABLE scrape_errors (
    key TEXT PRIMARY KEY NOT NULL,
    retailer TEXT NOT NULL,
    active BOOLEAN NOT NULL,
    reviewed BOOLEAN NOT NULL,
    last_seen TEXT NOT NULL,
    payload TEXT NOT NULL
);
CREATE INDEX scrape_errors_status ON scrape_errors(active, retailer);
CREATE INDEX alerts_expiry ON alerts(expires_at)
WHERE state IN ('active','paused','pending','failed');
CREATE INDEX alert_events_product_sequence ON alert_events(product_id, sequence);
CREATE INDEX alert_events_section_sequence ON alert_events(section, sequence);

CREATE TABLE feature_hype (
    feature_id TEXT NOT NULL,
    user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.US"+00:00"')),
    PRIMARY KEY (feature_id, user_id)
);
CREATE INDEX feature_hype_user ON feature_hype(user_id);

CREATE INDEX alert_events_batch ON alert_events(batch_id, sequence);

-- Public activity is independent of the short-lived alert processing queue.
CREATE TABLE catalog_activity (
    sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_key TEXT NOT NULL UNIQUE,
    observed_at TEXT NOT NULL,
    kind TEXT NOT NULL CHECK(kind IN ('added','edited','removed')),
    section TEXT NOT NULL,
    retailer TEXT NOT NULL,
    product_id TEXT NOT NULL,
    title TEXT NOT NULL,
    payload TEXT NOT NULL
);
CREATE INDEX catalog_activity_date ON catalog_activity(observed_at, sequence);

CREATE INDEX catalog_activity_timeline ON catalog_activity(observed_at DESC, product_id ASC, sequence DESC);

-- Pending signups are not users and cannot own sessions or account data.
CREATE TABLE pending_registrations (
    id TEXT PRIMARY KEY NOT NULL,
    email TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    expires_at TEXT NOT NULL
);
CREATE INDEX pending_registrations_email ON pending_registrations(email);
CREATE INDEX pending_registrations_expiry ON pending_registrations(expires_at);

CREATE TABLE registration_tokens (
    token_hash TEXT PRIMARY KEY NOT NULL,
    registration_id TEXT NOT NULL REFERENCES pending_registrations(id) ON DELETE CASCADE
);
CREATE INDEX registration_tokens_registration ON registration_tokens(registration_id);

CREATE TABLE guest_feature_hype (
    feature_id TEXT NOT NULL,
    browser_hash TEXT NOT NULL,
    PRIMARY KEY(feature_id, browser_hash)
);
CREATE INDEX guest_feature_hype_browser ON guest_feature_hype(browser_hash);

-- Preserve timeline ordering when filtering activity by retailer or category.
CREATE INDEX catalog_activity_section_timeline
    ON catalog_activity(section, observed_at DESC, product_id ASC, sequence DESC);
CREATE INDEX catalog_activity_retailer_timeline
    ON catalog_activity(retailer, observed_at DESC, product_id ASC, sequence DESC);
CREATE INDEX catalog_activity_retailer_section_timeline
    ON catalog_activity(retailer, section, observed_at DESC, product_id ASC, sequence DESC);

-- Active-slot counts need not scan an account's expired/delivered alert history.
CREATE INDEX alerts_user_live ON alerts(user_id, expires_at)
    WHERE state IN ('active', 'pending');

-- Staff curation and content.
CREATE FUNCTION valid_curation_components(value JSONB) RETURNS BOOLEAN
LANGUAGE sql IMMUTABLE AS $$
    SELECT CASE WHEN jsonb_typeof(value)='object' THEN NOT EXISTS (
        SELECT 1 FROM jsonb_each(value) entry WHERE NOT coalesce(
            jsonb_typeof(entry.value)='string' OR (
                jsonb_typeof(entry.value)='object'
                AND jsonb_typeof(entry.value->'id')='string'
                AND jsonb_typeof(entry.value->'label')='string'),false)
    ) ELSE false END
$$;

CREATE TABLE product_curation (
    product_id TEXT PRIMARY KEY REFERENCES products(id) ON DELETE CASCADE,
    title TEXT,
    description TEXT,
    image TEXT,
    components JSONB CHECK (components IS NULL OR valid_curation_components(components)),
    notes JSONB CHECK (notes IS NULL OR (jsonb_typeof(notes)='array'
        AND NOT jsonb_path_exists(notes, '$[*] ? (@.type() != "string")'))),
    approved BOOLEAN
);

CREATE TABLE scrape_error_reviews (
    error_key TEXT PRIMARY KEY REFERENCES scrape_errors(key) ON DELETE CASCADE,
    reviewed BOOLEAN NOT NULL DEFAULT true,
    note TEXT
);

CREATE TABLE retailers (
    id TEXT PRIMARY KEY,
    display_name TEXT NOT NULL,
    website TEXT,
    description TEXT
);

