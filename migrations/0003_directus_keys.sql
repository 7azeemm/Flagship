-- Directus requires a single-column primary key. Preserve the existing logical
-- uniqueness rules so wishlist inserts and vote merging keep their behavior.
ALTER TABLE wishlist_items
    DROP CONSTRAINT wishlist_items_pkey,
    ADD CONSTRAINT wishlist_items_user_target_key UNIQUE (user_id, target_type, target_id),
    ADD COLUMN id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY;

ALTER TABLE feature_hype
    DROP CONSTRAINT feature_hype_pkey,
    ADD CONSTRAINT feature_hype_feature_user_key UNIQUE (feature_id, user_id),
    ADD COLUMN id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY;

ALTER TABLE guest_feature_hype
    DROP CONSTRAINT guest_feature_hype_pkey,
    ADD CONSTRAINT guest_feature_hype_feature_browser_key UNIQUE (feature_id, browser_hash),
    ADD COLUMN id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY;
