-- URL-based edit history survives deleting and rebuilding the product catalog.
CREATE TABLE product_overrides (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_url TEXT NOT NULL CHECK (length(product_url) > 0),
    -- Keep the original RFC3339 text, including Rust's nanosecond precision.
    timestamp TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.US"Z"'))
        CHECK (timestamp::timestamptz IS NOT NULL),
    changes JSONB NOT NULL CHECK (jsonb_typeof(changes) = 'array' AND jsonb_array_length(changes) > 0),
    source TEXT NOT NULL DEFAULT 'directus'
);
CREATE INDEX product_overrides_url_history ON product_overrides(product_url, timestamp, id);

-- Preserve the original URL-keyed override documents, including edit timestamps.
INSERT INTO product_overrides(product_url, timestamp, changes, source)
SELECT saved.key, entry.value->>'timestamp', entry.value->'changes', 'legacy'
FROM app_state state
CROSS JOIN LATERAL jsonb_each(state.payload::jsonb) saved
CROSS JOIN LATERAL jsonb_array_elements(saved.value) entry
WHERE state.key = 'product_overrides' AND jsonb_array_length(entry.value->'changes') > 0;
DELETE FROM app_state WHERE key = 'product_overrides';

-- Convert any existing ID-based curation into the same URL-based history.
INSERT INTO product_overrides(product_url, timestamp, changes, source)
SELECT product.url, to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.US"Z"'), edits.changes, 'legacy-curation'
FROM product_curation curation
JOIN products product ON product.id = curation.product_id
CROSS JOIN LATERAL (
    SELECT jsonb_agg(jsonb_build_object('field', field.key,
        'old_value', product.payload::jsonb->field.key, 'new_value', field.value) ORDER BY field.key) AS changes
    FROM jsonb_each(jsonb_strip_nulls(jsonb_build_object(
        'title', curation.title, 'description', curation.description,
        'image', curation.image, 'components', curation.components,
        'notes', curation.notes, 'approved', curation.approved))) field
    WHERE product.payload::jsonb->field.key IS DISTINCT FROM field.value
) edits
WHERE edits.changes IS NOT NULL;

-- Keep the currently displayed curation in the product itself before removing
-- its overlay table. The migrated override remains available for future replay.
UPDATE products product SET payload = (
    product.payload::jsonb || jsonb_strip_nulls(jsonb_build_object(
        'title', curation.title, 'description', curation.description,
        'image', curation.image, 'components', curation.components,
        'notes', curation.notes, 'approved', curation.approved))
)::text
FROM product_curation curation WHERE curation.product_id = product.id;
DROP TABLE product_curation;
ALTER FUNCTION valid_curation_components(JSONB) RENAME TO valid_product_components;

-- Edits from Directus and explicitly marked Discord transactions are recorded
-- in the same transaction as the product update. Scrapes and replay skip this.
CREATE FUNCTION capture_product_override() RETURNS trigger LANGUAGE plpgsql
SET search_path=public,pg_temp AS $$
DECLARE
    old_product JSONB := OLD.payload::jsonb;
    edited_product JSONB := NEW.payload::jsonb;
    edit JSONB;
    changes JSONB;
    source TEXT;
    edited_at TEXT;
BEGIN
    IF current_user = 'flagship_directus' THEN
        source := 'directus';
    ELSIF current_setting('flagship.override_source', true) = 'discord' THEN
        source := 'discord';
    ELSE
        RETURN NEW;
    END IF;

    IF NEW.id IS DISTINCT FROM OLD.id OR edited_product->>'id' IS DISTINCT FROM OLD.id THEN
        RAISE EXCEPTION 'Product ID cannot be modified';
    END IF;

    IF source = 'directus' THEN
        -- Directus can edit these columns normally, or edit the complete JSON
        -- payload for title, components, notes, approval, and other fields.
        IF NEW.url IS DISTINCT FROM OLD.url THEN edited_product := jsonb_set(edited_product, '{url}', to_jsonb(NEW.url)); END IF;
        IF NEW.section IS DISTINCT FROM OLD.section THEN edited_product := jsonb_set(edited_product, '{section}', to_jsonb(NEW.section)); END IF;
        IF NEW.retailer IS DISTINCT FROM OLD.retailer THEN edited_product := jsonb_set(edited_product, '{retailer}', to_jsonb(NEW.retailer)); END IF;
        IF NEW.price IS DISTINCT FROM OLD.price THEN edited_product := jsonb_set(edited_product, '{price}', to_jsonb(NEW.price)); END IF;
        IF NEW.status IS DISTINCT FROM OLD.status THEN edited_product := jsonb_set(edited_product, '{status}', to_jsonb(NEW.status)); END IF;

        IF jsonb_typeof(edited_product) IS DISTINCT FROM 'object'
            OR NOT valid_product_components(edited_product->'components')
            OR jsonb_typeof(edited_product->'notes') IS DISTINCT FROM 'array'
            OR jsonb_path_exists(edited_product->'notes', '$[*] ? (@.type() != "string")')
            OR jsonb_typeof(edited_product->'images') IS DISTINCT FROM 'array'
            OR jsonb_path_exists(edited_product->'images', '$[*] ? (@.type() != "string")')
            OR jsonb_typeof(edited_product->'history') IS DISTINCT FROM 'array'
            OR jsonb_typeof(edited_product->'price') IS DISTINCT FROM 'number'
            OR jsonb_typeof(edited_product->'views') IS DISTINCT FROM 'number'
            OR jsonb_typeof(edited_product->'approved') IS DISTINCT FROM 'boolean'
            OR edited_product->>'status' NOT IN ('InStock','OutOfStock','Arriving','OnDemand')
            OR EXISTS (
                SELECT 1 FROM unnest(ARRAY['url','section','retailer','title','description','image','status']) field
                WHERE jsonb_typeof(edited_product->field) IS DISTINCT FROM 'string'
            ) THEN
            RAISE EXCEPTION 'Product payload has invalid or missing fields';
        END IF;

        SELECT jsonb_agg(jsonb_build_object('field', field.key,
            'old_value', old_product->field.key, 'new_value', field.value) ORDER BY field.key)
        INTO changes FROM jsonb_each(edited_product) field
        WHERE old_product ? field.key AND field.key NOT IN ('id','history','updated_at')
            AND old_product->field.key IS DISTINCT FROM field.value;
        IF changes IS NOT NULL THEN
            edited_at := to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.US"Z"');
            edit := jsonb_build_object('timestamp', edited_at, 'changes', changes);
            edited_product := jsonb_set(edited_product, '{history}', coalesce(old_product->'history', '[]'::jsonb) || jsonb_build_array(edit));
            edited_product := jsonb_set(edited_product, '{updated_at}', to_jsonb(edited_at));
        END IF;
        NEW.url := edited_product->>'url';
        NEW.section := edited_product->>'section';
        NEW.retailer := edited_product->>'retailer';
        NEW.price := (edited_product->>'price')::integer;
        NEW.status := edited_product->>'status';
        NEW.payload := edited_product::text;
    ELSE
        -- Discord already appended the exact field deltas to product history.
        -- Bulk saves may also flush view counters; those aren't manual edits.
        edit := edited_product->'history'->-1;
        IF edit IS NOT NULL AND NOT coalesce(old_product->'history', '[]'::jsonb) @> jsonb_build_array(edit) THEN
            changes := edit->'changes';
            edited_at := edit->>'timestamp';
        END IF;
    END IF;

    IF changes IS NOT NULL AND jsonb_array_length(changes) > 0 THEN
        INSERT INTO product_overrides(product_url, timestamp, changes, source)
        VALUES (OLD.url, edited_at, changes, source);
    END IF;
    IF NEW.payload IS DISTINCT FROM OLD.payload OR NEW.removed IS DISTINCT FROM OLD.removed THEN
        UPDATE admin_revision SET revision = revision + 1 WHERE id = 1;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER product_override_capture BEFORE UPDATE ON products
    FOR EACH ROW EXECUTE FUNCTION capture_product_override();
