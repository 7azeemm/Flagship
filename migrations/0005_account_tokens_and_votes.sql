-- One token store, with explicit ownership and purpose. Existing verification
-- links (including multiple resend links) retain their hashes and expiry.
CREATE TABLE account_tokens (
    id TEXT PRIMARY KEY,
    user_id TEXT REFERENCES users(id) ON DELETE CASCADE,
    registration_id TEXT REFERENCES pending_registrations(id) ON DELETE CASCADE,
    purpose TEXT NOT NULL CHECK (purpose IN ('verify_registration','verify_email','reset_password')),
    token_hash TEXT NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    used_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (num_nonnulls(user_id,registration_id)=1),
    CHECK ((purpose='verify_registration')=(registration_id IS NOT NULL))
);
INSERT INTO account_tokens(id,user_id,purpose,token_hash,expires_at,used_at,created_at)
SELECT id,user_id,purpose,token_hash,expires_at::timestamptz,used_at::timestamptz,created_at::timestamptz FROM email_tokens;
INSERT INTO account_tokens(id,registration_id,purpose,token_hash,expires_at)
SELECT 'registration:'||t.token_hash,t.registration_id,'verify_registration',t.token_hash,p.expires_at::timestamptz
FROM registration_tokens t JOIN pending_registrations p ON p.id=t.registration_id;
CREATE INDEX account_tokens_user_purpose ON account_tokens(user_id,purpose);
CREATE INDEX account_tokens_registration ON account_tokens(registration_id);
CREATE INDEX account_tokens_expiry ON account_tokens(expires_at);
DROP TABLE email_tokens,registration_tokens;

-- Signed-in and anonymous votes have the same lifecycle and counting rules.
CREATE TABLE feature_votes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feature_id TEXT NOT NULL,
    user_id TEXT REFERENCES users(id) ON DELETE CASCADE,
    browser_hash TEXT,
    created_at TIMESTAMPTZ DEFAULT now(),
    CHECK (num_nonnulls(user_id,browser_hash)=1),
    UNIQUE(feature_id,user_id),
    UNIQUE(feature_id,browser_hash)
);
INSERT INTO feature_votes(feature_id,user_id,created_at)
SELECT feature_id,user_id,created_at::timestamptz FROM feature_hype;
-- Older guest votes have no recorded date; preserve that unknown value.
INSERT INTO feature_votes(feature_id,browser_hash,created_at)
SELECT feature_id,browser_hash,NULL FROM guest_feature_hype;
CREATE INDEX feature_votes_user ON feature_votes(user_id);
CREATE INDEX feature_votes_browser ON feature_votes(browser_hash);
DROP TABLE feature_hype,guest_feature_hype;
